local fallback_colors = {
    background = "rgba(17130bff)",
    primary = "rgba(a3c9feff)",
    surface_variant = "rgba(43474eff)",
}

local function load_colors()
    local ok, colors = pcall(require, "generated.colors")
    if not ok or type(colors) ~= "table" then
        return fallback_colors
    end

    return setmetatable(colors, { __index = fallback_colors })
end

